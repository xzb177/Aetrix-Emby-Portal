import type { Component } from 'vue'
import {
  Clapperboard, ShoppingBag, User,
} from 'lucide-vue-next'

export interface NavItem {
  /** 显示名（顶栏与底部坞共用） */
  name: string
  /** 路由内路径，必须已在 src/router/index.ts 声明 */
  path: string
  icon: Component
}

